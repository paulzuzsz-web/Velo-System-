const RTL_LANGS = ['ar'];

function getLang() {
  const saved = localStorage.getItem('sh_lang');
  if (saved && LANGS[saved]) return saved;
  const nav = (navigator.language || 'de').slice(0, 2);
  return LANGS[nav] ? nav : 'de';
}

function setLang(code) {
  if (!LANGS[code]) return;
  localStorage.setItem('sh_lang', code);
  document.documentElement.lang = code;
  document.documentElement.dir = RTL_LANGS.includes(code) ? 'rtl' : 'ltr';
}

function t(key, params) {
  const lang = getLang();
  let str = (LANGS[lang] && LANGS[lang][key]) || LANGS.de[key] || key;
  if (params) for (const [k, v] of Object.entries(params)) str = str.replace('{' + k + '}', v);
  return str;
}

// Statische HTML-Elemente übersetzen
function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
}
